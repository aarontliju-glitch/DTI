// Helper to generate dynamic dates
export const getSlotDate = (dayOffset: number, hour: number, minute: number): string => {
  const d = new Date();
  d.setDate(d.getDate() + dayOffset);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
};

